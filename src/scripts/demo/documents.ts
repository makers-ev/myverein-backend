/**
 * Documents and PDF (Wave 13): club branding with a real logo, quota, the archive with folder rights, versions, trash and legal
 * hold, the personal storage, documents generated by the real render service, and a second version of two info pages. Every file
 * goes through the media layer (`createUploadedDocument`, `storeUpload`, `requestRender`), so the registry, the quota and the
 * checksums are real. PDFs are produced by the same engine that renders the generated documents.
 */

const CLUB_GREEN = "#1d5c3a";
const CLUB_ACCENT = "#2e7d32";
/** Quota of the demo club: small enough that the usage bar is visible. */
const DEMO_QUOTA_BYTES = 256 * 1024 * 1024;

/** A real, decodable PNG (RGB, two colours: a disc on a background); the club logo of the demo club. */
function logoPng(size = 96): Buffer {
  const rows: Buffer[] = [];
  const c = (size - 1) / 2;
  for (let y = 0; y < size; y++) {
    const row = Buffer.alloc(1 + size * 3);
    for (let x = 0; x < size; x++) {
      const inside = (x - c) ** 2 + (y - c) ** 2 <= (size * 0.42) ** 2;
      row.set(inside ? [0x1d, 0x5c, 0x3a] : [0xf2, 0xf7, 0xf3], 1 + x * 3);
    }
    rows.push(row);
  }
  const chunk = (type: string, data: Buffer) => {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "latin1"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body) >>> 0);
    return Buffer.concat([length, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 2, 0, 0, 0], 8);
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(Buffer.concat(rows))), chunk("IEND", Buffer.alloc(0))]);
}

/** Principal of a demo account for the render service (rights come from the account's club roles, like on a request). */
export async function principalOf(ctx: DemoCtx, key: string, roleTypes: string[]): Promise<DocumentPrincipal> {
  const p = accountOf(ctx, key);
  return { clubId: ctx.clubId, userId: p.userId, accountMemberId: p.memberId, clubMemberId: p.clubMemberId || null, roleTypes, departmentIds: [], isGuest: p.orgRole === "guest" };
}

/** Branding (colours, letterhead, logo) and the storage quota of the demo club. */
export async function seedBranding(ctx: DemoCtx): Promise<void> {
  const actor = accountOf(ctx, "vorsitz");
  const settings = {
    brandPrimaryColor: CLUB_GREEN,
    brandAccentColor: CLUB_ACCENT,
    letterheadAddress: "Sportplatzweg 1\n65000 Wiesbach",
    letterheadRegister: "Vereinsregister Wiesbach VR 1234",
    letterheadRepresentatives: "Vorstand: Heike Brandt, Thomas Lindner",
    letterheadContact: "vorstand@demo.myverein.local",
    letterheadFooter: "Demo Sportverein Wiesbach e.V. - Demo-Daten",
    storageQuotaBytes: DEMO_QUOTA_BYTES,
  };
  await db.insert(clubSettings).values({ clubId: ctx.clubId, ...settings }).onConflictDoUpdate({ target: clubSettings.clubId, set: { ...settings, updatedAt: new Date() } });
  const media = await storeUpload({
    file: new File([new Uint8Array(logoPng())], "logo.png", { type: "image/png" }),
    clubId: ctx.clubId,
    storagePrefix: `${ctx.clubId}/branding`,
    kind: "image",
    allowedTypes: ["image/png", "image/jpeg"],
    maxBytes: MAX_LOGO_BYTES,
    visibility: "club",
    owner: { type: DOCUMENT_OWNER_TYPES.branding, id: ctx.clubId },
    uploadedBy: actor.userId,
  });
  await db.update(clubSettings).set({ brandLogoKey: media.storageKey }).where(eq(clubSettings.clubId, ctx.clubId));
  await writeAudit(db, { eventType: "club_settings.update", subjectId: ctx.clubId, payload: { clubId: ctx.clubId, changedFields: ["branding.primaryColor", "branding.accentColor", "branding.letterheadAddress", "branding.logo"], changedBy: actor.memberId } });
  ctx.log("Branding (Farben, Briefkopf, Logo) und Speicher-Kontingent 256 MB");
}

/** A small real PDF with the club's branding. */
async function pdfFile(ctx: DemoCtx, filename: string, title: string, paragraphs: string[]): Promise<File> {
  const blocks: PdfBlock[] = [{ type: "heading", text: title }, ...paragraphs.map((text): PdfBlock => ({ type: "paragraph", text }))];
  const bytes = await getPdfEngine().render({ title, generatedAt: ctx.now, format: "a4", branding: await loadBranding(ctx.clubId), blocks }, DEFAULT_PDF_LIMITS);
  return new File([new Uint8Array(bytes)], filename, { type: "application/pdf" });
}

async function folder(ctx: DemoCtx, name: string, parentId: string | null, rights: Array<{ roleType?: string; departmentId?: string; level: "lesen" | "schreiben" | "verwalten" }>): Promise<string> {
  const actor = accountOf(ctx, "vorsitz");
  const [row] = await db.insert(documentFolders).values({ clubId: ctx.clubId, parentId, name, createdBy: actor.userId }).returning({ id: documentFolders.id });
  await writeAudit(db, { eventType: "document_folder.create", subjectId: row!.id, payload: { clubId: ctx.clubId, folderId: row!.id, parentId } });
  if (rights.length > 0) {
    await db.insert(documentPermissions).values(
      rights.map((r) =>
        r.roleType
          ? { clubId: ctx.clubId, folderId: row!.id, subjectType: "rolle", roleType: r.roleType, level: r.level, createdBy: actor.userId }
          : { clubId: ctx.clubId, folderId: row!.id, subjectType: "abteilung", departmentId: r.departmentId!, level: r.level, createdBy: actor.userId },
      ),
    );
    await writeAudit(db, { eventType: "document_folder.permissions", subjectId: row!.id, payload: { clubId: ctx.clubId, folderId: row!.id, entries: rights.length } });
  }
  return row!.id;
}

/** Document ids of the archive by key (used by the acknowledgement step). */
export const demoDocs: Record<string, string> = {};

/** Archive: three folders with rights (one inherited), uploads, a second version, a trashed document, a legal hold, two info page versions. */
export async function seedArchive(ctx: DemoCtx): Promise<void> {
  const actor = accountOf(ctx, "vorsitz");
  const rules = await folder(ctx, "Satzung & Ordnungen", null, [{ roleType: "trainer", level: "lesen" }, { roleType: "abteilungsleitung", level: "lesen" }]);
  const board = await folder(ctx, "Vorstand", null, []); // no entries: board only
  const contracts = await folder(ctx, "Verträge", board, []); // inherits from "Vorstand"
  const football = await folder(ctx, "Fußball", null, [{ departmentId: ctx.dept.fussball!, level: "lesen" }, { roleType: "abteilungsleitung", level: "schreiben" }]);

  const upload = async (key: string, folderId: string, title: string, paragraphs: string[], by = actor.userId): Promise<DocumentRow> => {
    const { document, version } = await createUploadedDocument({ clubId: ctx.clubId, scope: "verein", folderId, ownerClubMemberId: null, docType: "upload", title, file: await pdfFile(ctx, `${key}.pdf`, title, paragraphs), uploadedBy: by });
    await writeAudit(db, { eventType: "document.upload", subjectId: document.id, payload: { clubId: ctx.clubId, documentId: document.id, folderId, docType: "upload", sizeBytes: version.sizeBytes } });
    demoDocs[key] = document.id;
    return document;
  };

  const satzung = await upload("satzung", rules, "Satzung (Beschlussfassung)", ["Satzung des Demo Sportverein Wiesbach e.V. in der von der Mitgliederversammlung beschlossenen Fassung.", "Dies ist ein Demo-Dokument."]);
  const v2 = await addUploadedVersion(satzung, await pdfFile(ctx, "satzung-v2.pdf", "Satzung (Beschlussfassung)", ["Fassung mit geänderter Einladungsfrist in § 10.", "Dies ist ein Demo-Dokument."]), actor.userId, "Einladungsfrist in § 10 angepasst");
  await writeAudit(db, { eventType: "document.version_add", subjectId: satzung.id, payload: { clubId: ctx.clubId, documentId: satzung.id, versionNo: v2.version.versionNo, sizeBytes: v2.version.sizeBytes } });
  await upload("hausordnung", rules, "Hausordnung Vereinsheim", ["1. Das Vereinsheim ist sauber zu hinterlassen.", "2. Der letzte Nutzer schließt ab und trägt sich im Schlüsselbuch ein.", "3. Ab 22 Uhr ist Nachtruhe."]);
  await upload("freizeit", rules, "Einverständniserklärung Ferienfreizeit", ["Hiermit erkläre ich mich damit einverstanden, dass mein Kind an der Ferienfreizeit des Vereins teilnimmt.", "Dies ist ein Demo-Dokument."]);
  await upload("trainingsplan", football, "Trainingsplan Winter", ["Dienstag und Donnerstag 18:30 Uhr, Kunstrasenplatz.", "Bei Sperrung des Platzes weichen wir in die Halle aus."]);

  const lease = await upload("platzpacht", contracts, "Pachtvertrag Sportplatz", ["Pachtvertrag zwischen der Gemeinde Wiesbach und dem Verein.", "Dies ist ein Demo-Dokument."]);
  // Legal hold with a reason (kept out of the audit log, like the route).
  await db.update(documents).set({ legalHold: true, legalHoldReason: "Pachtzins wird mit der Gemeinde noch geklärt", updatedAt: new Date() }).where(eq(documents.id, lease.id));
  await writeAudit(db, { eventType: "document.legal_hold", subjectId: lease.id, actorUserId: actor.userId, clubId: ctx.clubId, payload: { clubId: ctx.clubId, documentId: lease.id, active: true } });

  const old = await upload("alt", board, "Mitgliederliste 2022 (veraltet)", ["Alte Liste, ersetzt durch die aktuelle Mitgliederliste."]);
  await db.update(documents).set({ status: "im_papierkorb", trashedAt: new Date(ctx.now.getTime() - 3 * 86_400_000), trashedBy: actor.userId, updatedAt: new Date() }).where(eq(documents.id, old.id));
  await writeAudit(db, { eventType: "document.trash", subjectId: old.id, payload: { clubId: ctx.clubId, documentId: old.id } });

  // Info pages: a second version each (the Satzung page gets the PDF attached, the house rules get changed text).
  const pageUser = actor.userId;
  await db.transaction(async (tx) => {
    const base = { clubId: ctx.clubId, validFrom: null, externalUrl: null, userId: pageUser };
    const [satzungPage] = await tx.execute<{ title: string; content_markdown: string | null }>(sql`SELECT title, content_markdown FROM club_info_pages WHERE club_id = ${ctx.clubId} AND slug = 'satzung'`).then((r) => r.rows);
    const [hausPage] = await tx.execute<{ title: string; content_markdown: string | null }>(sql`SELECT title, content_markdown FROM club_info_pages WHERE club_id = ${ctx.clubId} AND slug = 'hausordnung'`).then((r) => r.rows);
    await writeInfoPage(tx, { ...base, slug: "satzung", title: satzungPage!.title, contentMarkdown: satzungPage!.content_markdown, documentId: satzung.id, note: "Satzung als PDF angehängt" });
    await writeInfoPage(tx, { ...base, slug: "hausordnung", title: hausPage!.title, contentMarkdown: `${hausPage!.content_markdown}\n4. Müll wird mitgenommen oder in der Tonne am Eingang entsorgt.`, documentId: null, note: "Punkt 4 ergänzt" });
  });
  ctx.log("Dokumentenarchiv: 4 Ordner (Rechte, geerbt), 6 Dokumente, 2 Versionen, 1 im Papierkorb, 1 Aufbewahrungssperre, 2 Info-Seiten-Versionen");
}

/** Personal storage (a member, a child filed by the guardian) and documents generated by the real render service. */
export async function seedGeneratedAndPersonal(ctx: DemoCtx): Promise<void> {
  registerBuiltinTemplates();
  const board = await principalOf(ctx, "vorsitz", ["vorsitz"]);
  const lukas = await principalOf(ctx, "mitglied", []);
  const mitglied = clubMemberOf(ctx, "mitglied");

  const own = await createUploadedDocument({
    clubId: ctx.clubId, scope: "person", folderId: null, ownerClubMemberId: mitglied, docType: "upload", title: "Sportärztliches Attest", file: await pdfFile(ctx, "attest.pdf", "Sportärztliches Attest", ["Demo-Attest: sporttauglich.", "Dies ist ein Demo-Dokument."]), uploadedBy: accountOf(ctx, "mitglied").userId, selfService: true,
  });
  await writeAudit(db, { eventType: "member_document.upload", subjectId: mitglied, actorUserId: accountOf(ctx, "mitglied").userId, clubId: ctx.clubId, payload: { clubId: ctx.clubId, clubMemberId: mitglied, documentId: own.document.id, sizeBytes: own.version.sizeBytes, via: "self" } });
  const child = await createUploadedDocument({
    clubId: ctx.clubId, scope: "person", folderId: null, ownerClubMemberId: clubMemberOf(ctx, "noah"), docType: "upload", title: "Kopie Impfpass", file: await pdfFile(ctx, "impfpass.pdf", "Kopie Impfpass", ["Demo-Dokument für ein Kind, abgelegt von der Erziehungsberechtigten."]), uploadedBy: accountOf(ctx, "eltern").userId, selfService: true,
  });
  await writeAudit(db, { eventType: "member_document.upload", subjectId: clubMemberOf(ctx, "noah"), actorUserId: accountOf(ctx, "eltern").userId, clubId: ctx.clubId, payload: { clubId: ctx.clubId, clubMemberId: clubMemberOf(ctx, "noah"), documentId: child.document.id, sizeBytes: child.version.sizeBytes, via: "guardian" } });
  // The board looked at the member's certificate: the member sees this entry in the access log of the own storage.
  await writeAudit(db, { eventType: "member_document.board_access", subjectId: mitglied, actorUserId: board.userId, clubId: ctx.clubId, payload: { clubId: ctx.clubId, clubMemberId: mitglied, documentId: own.document.id, action: "download" } });

  const [application] = await db.select({ id: clubApplications.id }).from(clubApplications).where(and(eq(clubApplications.clubId, ctx.clubId), eq(clubApplications.status, "approved"), eq(clubApplications.clubMemberId, mitglied))).limit(1);
  const jobs = [
    () => requestRender({ clubId: ctx.clubId, templateId: "mitgliedsbestaetigung", params: { clubMemberId: mitglied }, actor: lukas }),
    () => requestRender({ clubId: ctx.clubId, templateId: "mitgliederliste", params: {}, actor: board }),
    () => requestRender({ clubId: ctx.clubId, templateId: "jahresbericht", params: {}, actor: board }),
    ...(application ? [() => requestRender({ clubId: ctx.clubId, templateId: "aufnahme-beleg", params: { applicationId: application.id }, actor: board })] : []),
  ];
  // Sequential on purpose: the system folders are created on first use.
  let done = 0;
  for (const job of jobs) {
    const result = await job();
    if (result.status !== "fertig") throw new Error(`Demo render job ${result.templateId} ended as ${result.status} (${result.errorCode ?? "no code"})`);
    done++;
  }
  await checkStorageThresholds(ctx.clubId);
  ctx.log(`Persönliche Ablage (2 Uploads) und ${done} erzeugte PDFs (Mitgliedsbestätigung, Mitgliederliste, Jahresbericht, Aufnahmebeleg)`);
}
