import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { ERROR_CODES } from "../lib/error-codes.js";

/**
 * Generates the README section "Error codes" (Wave 14 DS2). Top-level codes come from `lib/error-codes.ts`; the specific
 * `error.details.code` reasons are found by scanning the sources for `details: { code: "x" }` and the `fail.conflict|invalid(msg, "x")`
 * helpers, with the HTTP status of the error class thrown on the same line. Codes built dynamically (CSV row problems, form
 * publishing problems, erasure blockers) are documented where they are produced and are not part of this scan.
 *

 * Dev tooling: reads and writes only source files and README.md (excluded from the media grep gate like scratch-db.ts), never user files.
 *
 * `npm run docs:error-codes` rewrites the block between the markers; `error-codes.test.ts` fails if the README is stale.
 */

export const BEGIN = "<!-- error-codes:begin (generated by npm run docs:error-codes) -->";
export const END = "<!-- error-codes:end -->";

const srcRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const STATUS_BY_CLASS: Record<string, number> = { BadRequestError: 400, UnauthorizedError: 401, ForbiddenError: 403, NotFoundError: 404, ConflictError: 409, ValidationError: 422, TooManyRequestsError: 429, ServiceUnavailableError: 503, InternalError: 500 };
const STATUS_BY_FAIL: Record<string, number> = { conflict: 409, invalid: 422 };

export interface DetailCode {
  code: string;
  statuses: number[];
  files: string[];
}

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...sourceFiles(full));
    else if (name.endsWith(".ts") && !name.endsWith(".test.ts")) out.push(full);
  }
  return out;
}

function statusOfLine(line: string, index: number): number | null {
  const before = line.slice(0, index);
  const klass = [...before.matchAll(/\b(\w+Error)\b/g)].filter((m) => m[1]! in STATUS_BY_CLASS).pop();
  const helper = [...before.matchAll(/\bfail\.(conflict|invalid)\(/g)].pop();
  if (klass && (!helper || klass.index! > helper.index!)) return STATUS_BY_CLASS[klass[1]!]!;
  if (helper) return STATUS_BY_FAIL[helper[1]!]!;
  return null;
}

/** All specific `details.code` reasons found in the source, sorted by code. */
export function scanDetailCodes(): DetailCode[] {
  const found = new Map<string, { statuses: Set<number>; files: Set<string> }>();
  for (const file of ["routes", "lib", "middleware"].flatMap((d) => sourceFiles(join(srcRoot, d)))) {
    const rel = relative(srcRoot, file).replace(/\\/g, "/");
    for (const line of readFileSync(file, "utf8").split("\n")) {
      const hits = [
        ...[...line.matchAll(/details:\s*\{\s*code:\s*"([a-z][a-z0-9_]*)"/g)].map((m) => ({ code: m[1]!, at: m.index! })),
        ...[...line.matchAll(/\bfail\.(?:conflict|invalid)\((?:"(?:[^"\\]|\\.)*"|`[^`]*`),\s*"([a-z][a-z0-9_]*)"/g)].map((m) => ({ code: m[1]!, at: m.index! + m[0].length })),
      ];
      for (const { code, at } of hits) {
        const entry = found.get(code) ?? { statuses: new Set<number>(), files: new Set<string>() };
        const status = statusOfLine(line, at);
        if (status !== null) entry.statuses.add(status);
        entry.files.add(rel);
        found.set(code, entry);
      }
    }
  }
  return [...found.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([code, e]) => ({ code, statuses: [...e.statuses].sort(), files: [...e.files].sort() }));
}

export function renderErrorCodeBlock(): string {
  const top = Object.entries(ERROR_CODES).map(([code, e]) => `| \`${code}\` | ${e.status} | ${e.meaning} |`);
  const details = scanDetailCodes().map((d) => `| \`${d.code}\` | ${d.statuses.length > 0 ? d.statuses.join(", ") : "see route"} | ${d.files.map((f) => `\`${f}\``).join(", ")} |`);
  return [
    BEGIN,
    "",
    "**Top-level `error.code`** (body `{ error: { code, message, details? } }`):",
    "",
    "| Code | HTTP | Meaning |",
    "|---|---|---|",
    ...top,
    "",
    "**Specific reasons `error.details.code`** (snake_case, stable, found by scanning the source; clients map these to texts, never show `message`):",
    "",
    "| `details.code` | HTTP | Thrown in |",
    "|---|---|---|",
    ...details,
    "",
    END,
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const readme = join(srcRoot, "..", "README.md");
  const text = readFileSync(readme, "utf8");
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < 0) throw new Error("README.md has no error-codes markers");
  writeFileSync(readme, text.slice(0, start) + renderErrorCodeBlock() + text.slice(end + END.length));
  console.log("README.md error codes updated");
}
