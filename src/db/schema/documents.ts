import { sql } from "drizzle-orm";
import { boolean, check, date, index, integer, jsonb, pgTable, text, timestamp, uniqueIndex, uuid, type AnyPgColumn } from "drizzle-orm/pg-core";

import { organization, user } from "../../auth/auth-schema.js";
import { clubMembers } from "./club-members.js";
import { departments } from "./departments.js";

/** `documents.scope`: club archive vs. personal storage of one member (with or without account). */
export const DOCUMENT_SCOPES = ["verein", "person"] as const;
export type DocumentScope = (typeof DOCUMENT_SCOPES)[number];

/** `documents.kind`: generated by the render pipeline (snapshot) vs. uploaded by a person. */
export const DOCUMENT_KINDS = ["erzeugt", "hochgeladen"] as const;
export type DocumentKind = (typeof DOCUMENT_KINDS)[number];

export const DOCUMENT_STATUSES = ["aktiv", "im_papierkorb", "zur_loeschung"] as const;
export type DocumentStatus = (typeof DOCUMENT_STATUSES)[number];

export const DOCUMENT_PERMISSION_LEVELS = ["lesen", "schreiben", "verwalten"] as const;
export type DocumentPermissionLevel = (typeof DOCUMENT_PERMISSION_LEVELS)[number];

export const DOCUMENT_SUBJECT_TYPES = ["rolle", "abteilung", "mitglied"] as const;
export type DocumentSubjectType = (typeof DOCUMENT_SUBJECT_TYPES)[number];

/** Maximum folder nesting (root folders have depth 1); enforced by the API. */
export const MAX_FOLDER_DEPTH = 5;

/** Folder tree of the club archive (Wave 13 B5). Folders are club-wide; the personal storage has no folders. */
export const documentFolders = pgTable(
  "document_folders",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    parentId: uuid("parent_id").references((): AnyPgColumn => documentFolders.id, { onDelete: "restrict" }),
    name: text("name").notNull(),
    // System folders (e.g. "Protokolle") are created by the pipeline for generated documents and cannot be renamed or removed.
    systemKey: text("system_key"),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("document_folders_club_parent_idx").on(table.clubId, table.parentId),
    uniqueIndex("document_folders_system_key_uidx").on(table.clubId, table.systemKey).where(sql`${table.systemKey} IS NOT NULL`),
  ],
);

/**
 * Rights on a folder per role / department / single club member (deny-by-default: no row = no access). Inherited by
 * sub-folders unless a sub-folder carries its own rows (the nearest folder with rows decides).
 */
export const documentPermissions = pgTable(
  "document_permissions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    folderId: uuid("folder_id")
      .notNull()
      .references(() => documentFolders.id, { onDelete: "cascade" }),
    // One of DOCUMENT_SUBJECT_TYPES.
    subjectType: text("subject_type").notNull(),
    roleType: text("role_type"),
    departmentId: uuid("department_id").references(() => departments.id, { onDelete: "cascade" }),
    clubMemberId: uuid("club_member_id").references(() => clubMembers.id, { onDelete: "cascade" }),
    // One of DOCUMENT_PERMISSION_LEVELS.
    level: text("level").notNull(),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("document_permissions_folder_idx").on(table.folderId),
    uniqueIndex("document_permissions_role_uidx").on(table.folderId, table.roleType).where(sql`${table.subjectType} = 'rolle'`),
    uniqueIndex("document_permissions_department_uidx").on(table.folderId, table.departmentId).where(sql`${table.subjectType} = 'abteilung'`),
    uniqueIndex("document_permissions_member_uidx").on(table.folderId, table.clubMemberId).where(sql`${table.subjectType} = 'mitglied'`),
    check(
      "document_permissions_subject_chk",
      sql`(${table.subjectType} = 'rolle' AND ${table.roleType} IS NOT NULL AND ${table.departmentId} IS NULL AND ${table.clubMemberId} IS NULL)
        OR (${table.subjectType} = 'abteilung' AND ${table.departmentId} IS NOT NULL AND ${table.roleType} IS NULL AND ${table.clubMemberId} IS NULL)
        OR (${table.subjectType} = 'mitglied' AND ${table.clubMemberId} IS NOT NULL AND ${table.roleType} IS NULL AND ${table.departmentId} IS NULL)`,
    ),
  ],
);

/**
 * A document (metadata). The bytes live in `document_versions` -> `media_files` (central media layer); this row never
 * holds a file URL or key. `scope = verein` documents sit in the archive (optionally in a folder), `scope = person`
 * documents in the personal storage of `owner_club_member_id`.
 */
export const documents = pgTable(
  "documents",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    // One of DOCUMENT_SCOPES.
    scope: text("scope").notNull(),
    folderId: uuid("folder_id").references(() => documentFolders.id, { onDelete: "restrict" }),
    ownerClubMemberId: uuid("owner_club_member_id").references(() => clubMembers.id, { onDelete: "cascade" }),
    // One of DOCUMENT_KINDS.
    kind: text("kind").notNull(),
    // Free classification ("upload", "aufnahmebeleg", "mitgliederliste", ...): drives retention (B14) and sensitivity.
    docType: text("doc_type").notNull().default("upload"),
    title: text("title").notNull(),
    // Latest version; NULL only while the first version is being written.
    currentVersionId: uuid("current_version_id").references((): AnyPgColumn => documentVersions.id, { onDelete: "set null" }),
    // One of DOCUMENT_STATUSES.
    status: text("status").notNull().default("aktiv"),
    // The owner hid a generated document from the own list (it is kept for evidence).
    hiddenByOwner: boolean("hidden_by_owner").notNull().default(false),
    trashedAt: timestamp("trashed_at", { withTimezone: true }),
    trashedBy: text("trashed_by").references(() => user.id, { onDelete: "set null" }),
    retentionUntil: date("retention_until", { mode: "string" }),
    legalHold: boolean("legal_hold").notNull().default(false),
    // Why the hold was set (board note, max 200 characters); cleared with the hold. Shown to managers only, never in the audit log.
    legalHoldReason: text("legal_hold_reason"),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("documents_club_folder_idx").on(table.clubId, table.folderId),
    index("documents_owner_idx").on(table.ownerClubMemberId),
    index("documents_retention_idx").on(table.retentionUntil).where(sql`${table.retentionUntil} IS NOT NULL`),
    index("documents_club_status_idx").on(table.clubId, table.status),
    check("documents_scope_chk", sql`(${table.scope} = 'verein' AND ${table.ownerClubMemberId} IS NULL) OR (${table.scope} = 'person' AND ${table.ownerClubMemberId} IS NOT NULL AND ${table.folderId} IS NULL)`),
  ],
);

/**
 * One stored file of a document (never edited, a change is a new version). For generated documents the render input is
 * recorded (template id + version, input hash, engine version) so the snapshot is explainable; it is never re-rendered on read.
 */
export const documentVersions = pgTable(
  "document_versions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    documentId: uuid("document_id")
      .notNull()
      .references(() => documents.id, { onDelete: "cascade" }),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    versionNo: integer("version_no").notNull(),
    // Key into `media_files` (central media layer).
    storageKey: text("storage_key").notNull(),
    mimeType: text("mime_type").notNull(),
    sizeBytes: integer("size_bytes").notNull(),
    sha256: text("sha256").notNull(),
    originalFilename: text("original_filename").notNull(),
    note: text("note"),
    templateId: text("template_id"),
    templateVersion: integer("template_version"),
    inputHash: text("input_hash"),
    engineVersion: text("engine_version"),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [uniqueIndex("document_versions_doc_no_uidx").on(table.documentId, table.versionNo), index("document_versions_club_idx").on(table.clubId)],
);

/** `abgelaufen` is derived at read time (an open request past its due date); it is never written to the column. */
export const ACK_STATUSES = ["offen", "bestaetigt", "abgelehnt", "abgelaufen"] as const;
export const ACK_GIVEN_BY = ["self", "guardian", "board_paper"] as const;
export type AckStatus = (typeof ACK_STATUSES)[number];

/** Simple digital acknowledgement of a document version (Wave 13 B11): who, when, which version (hash), exact wording, on behalf of whom. */
export const documentAcknowledgements = pgTable(
  "document_acknowledgements",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    documentId: uuid("document_id")
      .notNull()
      .references(() => documents.id, { onDelete: "cascade" }),
    versionId: uuid("version_id")
      .notNull()
      .references(() => documentVersions.id, { onDelete: "cascade" }),
    sha256: text("sha256").notNull(),
    // The person the acknowledgement is about (a child's row is acted on by a guardian).
    clubMemberId: uuid("club_member_id")
      .notNull()
      .references(() => clubMembers.id, { onDelete: "cascade" }),
    // One of ACK_STATUSES.
    status: text("status").notNull().default("offen"),
    wording: text("wording").notNull(),
    requestedBy: text("requested_by").references(() => user.id, { onDelete: "set null" }),
    requestedAt: timestamp("requested_at", { withTimezone: true }).notNull().defaultNow(),
    dueAt: timestamp("due_at", { withTimezone: true }),
    respondedAt: timestamp("responded_at", { withTimezone: true }),
    actedByUserId: text("acted_by_user_id").references(() => user.id, { onDelete: "set null" }),
    actedByClubMemberId: uuid("acted_by_club_member_id").references(() => clubMembers.id, { onDelete: "set null" }),
    // Same proof structure as `consent_records`: who gave it (`self` / `guardian` / `board_paper`), and for a paper proof the date and source.
    givenBy: text("given_by"),
    proofDate: date("proof_date", { mode: "string" }),
    proofSource: text("proof_source"),
    // The person has to enter the password again to confirm (sensitive documents such as a liability waiver).
    requiresReauth: boolean("requires_reauth").notNull().default(false),
    remindedAt: timestamp("reminded_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("document_ack_version_member_uidx").on(table.versionId, table.clubMemberId),
    index("document_ack_club_status_idx").on(table.clubId, table.status),
    index("document_ack_member_idx").on(table.clubMemberId),
    check("document_ack_given_by_chk", sql`${table.givenBy} IS NULL OR ${table.givenBy} IN ('self', 'guardian', 'board_paper')`),
    check("document_ack_paper_proof_chk", sql`${table.givenBy} IS DISTINCT FROM 'board_paper' OR (${table.proofDate} IS NOT NULL AND ${table.proofSource} IS NOT NULL)`),
  ],
);

export const CARD_STATUSES = ["aktiv", "widerrufen"] as const;
export type CardStatus = (typeof CARD_STATUSES)[number];

/**
 * Digital membership card per club member (with or without account). The id is the opaque card id inside the signed QR
 * token; `token_version` is bumped by a re-issue, which invalidates every earlier token. Validity itself is derived live
 * from the member (status, `left_at`), not stored here.
 */
export const memberCards = pgTable(
  "member_cards",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    clubMemberId: uuid("club_member_id")
      .notNull()
      .references(() => clubMembers.id, { onDelete: "cascade" }),
    // One of CARD_STATUSES.
    status: text("status").notNull().default("aktiv"),
    tokenVersion: integer("token_version").notNull().default(1),
    validUntil: date("valid_until", { mode: "string" }),
    issuedAt: timestamp("issued_at", { withTimezone: true }).notNull().defaultNow(),
    issuedBy: text("issued_by").references(() => user.id, { onDelete: "set null" }),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    revokedReason: text("revoked_reason"),
  },
  (table) => [uniqueIndex("member_cards_club_member_uidx").on(table.clubMemberId), index("member_cards_club_idx").on(table.clubId)],
);

export const RENDER_JOB_STATUSES = ["wartet", "rendert", "fertig", "fehlgeschlagen"] as const;
export type RenderJobStatus = (typeof RENDER_JOB_STATUSES)[number];

/** One PDF generation (Wave 13 B8). `params` holds ids and options only, never personal data; failures carry a fixed code. */
export const renderJobs = pgTable(
  "render_jobs",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: text("club_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    templateId: text("template_id").notNull(),
    templateVersion: integer("template_version").notNull(),
    // One of RENDER_JOB_STATUSES.
    status: text("status").notNull().default("wartet"),
    params: jsonb("params").$type<Record<string, unknown>>().notNull().default({}),
    requestedBy: text("requested_by").references(() => user.id, { onDelete: "set null" }),
    // Person the document is about (personal storage target), if any.
    subjectClubMemberId: uuid("subject_club_member_id").references(() => clubMembers.id, { onDelete: "cascade" }),
    documentId: uuid("document_id").references(() => documents.id, { onDelete: "set null" }),
    versionId: uuid("version_id").references(() => documentVersions.id, { onDelete: "set null" }),
    inputHash: text("input_hash"),
    attempts: integer("attempts").notNull().default(0),
    errorCode: text("error_code"),
    startedAt: timestamp("started_at", { withTimezone: true }),
    finishedAt: timestamp("finished_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [index("render_jobs_club_status_idx").on(table.clubId, table.status), index("render_jobs_subject_idx").on(table.subjectClubMemberId)],
);

export type DocumentRow = typeof documents.$inferSelect;
export type DocumentVersionRow = typeof documentVersions.$inferSelect;
export type DocumentFolderRow = typeof documentFolders.$inferSelect;
export type DocumentPermissionRow = typeof documentPermissions.$inferSelect;
export type MemberCardRow = typeof memberCards.$inferSelect;
export type RenderJobRow = typeof renderJobs.$inferSelect;
